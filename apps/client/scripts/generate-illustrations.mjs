/**
 * Generates `src/data/illustrations.ts`: a static map from the card `illustration` paths
 * (e.g. `cards/26_1.jpg`) to bundled image assets. Metro only bundles images referenced by a
 * literal `require()`, so run this script whenever an image is added to `assets/cards/`.
 */
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const imagesDir = path.join(root, 'assets/cards');
const output = path.join(root, 'src/data/illustrations.ts');

const files = readdirSync(imagesDir)
  .filter(file => /\.(jpe?g|png|webp)$/i.test(file))
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }));

const lines = files.map(file => `  'cards/${file}': require('../../assets/cards/${file}'),`);

writeFileSync(
  output,
  `/* eslint-disable @typescript-eslint/no-require-imports */
// Generated by scripts/generate-illustrations.mjs — do not edit manually.
import type { ImageSourcePropType } from 'react-native';

export const illustrations: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};
`,
);

console.warn(`Generated ${files.length} illustrations in ${path.relative(root, output)}`);
